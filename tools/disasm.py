#!/usr/bin/env python3
"""Disassemble a project's original blocks with da65 and prove they rebuild byte for byte.

Run from the project root:   python3 tools/disasm.py [--check]

Reads tools/symbols.py (the master for names, ranges and comments; LABELS, RANGES and INLINE apply to
every block, and a block's own "labels", "ranges" and "inline" add to them), and for each block:
  1. reads the original bytes (a PRG, an Oric TAP block, or a raw binary) without changing them;
  2. traces code by recursive descent from the block's entries (tools/trace6502.py's opcode table);
  3. writes src/<block>.s through a da65 info file, with names, block comments, inline comments
     and the original address in the comment column;
  4. reassembles it with cl65 and compares every byte with the original (the PRG header too).

--check  rebuild and compare only; leave src/ untouched (for CI and `make verify`).
Exit status 1 if any block differs. Never edit src/*.s by hand in this pipeline: change symbols.py.
"""
import argparse
import importlib.util
import re
import subprocess
import sys
import tempfile
from pathlib import Path

TOOLS = Path(__file__).resolve().parent
ROOT = TOOLS.parent
sys.path.insert(0, str(TOOLS))
from hw_labels import MACHINES  # noqa: E402
from media import read_prg, tap_blocks  # noqa: E402
from trace6502 import LEN, OPS  # noqa: E402


def load_symbols():
    spec = importlib.util.spec_from_file_location("symbols", TOOLS / "symbols.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def original(block):
    """Return (start, data, header_bytes) for a block; header_bytes is the PRG address or b''."""
    path = ROOT / block["file"]
    kind = block.get("kind", "prg")
    if kind == "prg":
        load, data = read_prg(path)
        return load, data, path.read_bytes()[:2]
    if kind == "tap":
        b = list(tap_blocks(path))[block.get("index", 0)]
        return b["start"], b["data"], b""
    if kind == "c16tap":  # a program file on a raw C16 tape, decoded by tools/c16_tap.py
        from c16_tap import programs
        prog = programs(path)[block.get("index", 0)]
        return prog["start"], prog["data"], b""
    if kind == "raw":
        return block["start"], path.read_bytes(), b""
    raise ValueError(f"unknown kind {kind!r}")


def trace(data, base, entries, data_bytes=frozenset()):
    """Recursive descent from the entries; returns (code byte set, opcodes that stopped a path).

    A path stops quietly at bytes symbols.py declares as data (inline JSR parameters, tables)."""
    end = base + len(data)
    todo, code, bad = list(entries), set(), []
    while todo:
        pc = todo.pop()
        while base <= pc < end and pc not in code and pc not in data_bytes:
            o = data[pc - base]
            if o not in OPS:
                bad.append(pc)
                break
            mn, md = OPS[o]
            n = LEN[md]
            if pc + n > end:
                bad.append(pc)
                break
            code.update(range(pc, pc + n))
            arg = data[pc - base + 1] | (data[pc - base + 2] << 8 if n == 3 else 0) if n > 1 else None
            nxt = pc + n
            if md == "rel":
                todo.append(nxt + (arg - 256 if arg > 127 else arg))
            elif mn == "JSR":
                todo.append(arg)
            elif mn == "JMP":
                if md == "abs":
                    todo.append(arg)
                break
            elif mn in ("RTS", "RTI", "BRK"):
                break
            pc = nxt
    return code, bad


def ranges_for(data, base, code, overrides):
    kinds = ["ByteTable"] * len(data)
    for a in code:
        kinds[a - base] = "Code"
    for a, b, typ, *_ in overrides:  # symbols.py ranges win over the trace
        for x in range(max(a, base), min(b, base + len(data) - 1) + 1):
            kinds[x - base] = typ
    out = []
    for i, k in enumerate(kinds):
        if out and out[-1][2] == k:
            out[-1][1] = base + i
        else:
            out.append([base + i, base + i, k])
    return out


def info_file(binpath, base, size, ranges, labels, sizes=None):
    lines = [f'GLOBAL {{ INPUTNAME "{binpath}"; STARTADDR ${base:04X}; INPUTSIZE {size}; CPU "6502"; COMMENTS 4; }};']
    lines += [f'RANGE {{ START ${a:04X}; END ${b:04X}; TYPE {t}; }};' for a, b, t in ranges]
    sizes = sizes or {}
    lines += [f'LABEL {{ NAME "{name}"; ADDR ${a:04X};' + (f' SIZE {sizes[a]};' if a in sizes else '') + ' };'
              for a, name in sorted(labels.items())]
    return "\n".join(lines) + "\n"


def postprocess(raw, title, notes, inline):
    out = [f"; {title}", "; Generated by tools/disasm.py from tools/symbols.py: edit symbols.py, not this file.", ""]
    for line in raw.splitlines():
        if line.startswith(("; da65", "; Created", "; Input file", "; Page")) or line.startswith("; " + "-" * 70):
            continue
        m = re.match(r"^(\w+):", line)
        if m and m.group(1) in notes:
            out += ["", "; " + "-" * 74] + [("; " + t).rstrip() for t in notes[m.group(1)].splitlines()] + ["; " + "-" * 74]
        m = re.search(r";\s([0-9A-F]{4})\s(?:[0-9A-F]{2}\s)+.*$", line)
        if m:
            a = int(m.group(1), 16)
            c = inline.get(a, "")
            line = f"{line[:m.start()].rstrip():<40}; {a:04X}" + (f"  {c}" if c else "")
        out.append(line.rstrip())
    # da65 declares every label outside the block; keep only the ones the code uses.
    text = "\n".join(out)
    kept = []
    for line in out:
        m = re.match(r"^(\w+)\s*:=\s*\$[0-9A-F]+", line)
        if m and not re.search(rf"\b{m.group(1)}\b", text[text.index(line) + len(line):]):
            continue
        kept.append(line)
    return "\n".join(kept) + "\n"


def build(block, sym, check_only):
    name = block["name"]
    base, data, header = original(block)
    labels = {a: n for a, n in MACHINES[sym.MACHINE].items() if not base <= a < base + len(data)}
    notes = {}
    inline = {**getattr(sym, "INLINE", {}), **block.get("inline", {})}
    for a, (lab, note) in {**getattr(sym, "LABELS", {}), **block.get("labels", {})}.items():
        labels[a] = lab
        if note and base <= a < base + len(data):
            notes[lab] = note
    overrides = [r for r in getattr(sym, "RANGES", []) + block.get("ranges", []) if base <= r[0] < base + len(data)]
    for a, b, typ, lab, note in overrides:
        if lab:
            labels[a] = lab
            if note:
                notes[lab] = note
    data_bytes = {x for a, b, typ, *_ in overrides if typ != "Code" for x in range(a, b + 1)}
    code, bad = trace(data, base, block.get("entries", []), data_bytes)
    ranges = ranges_for(data, base, code, overrides)

    build_dir = ROOT / "build"
    build_dir.mkdir(exist_ok=True)
    binpath = build_dir / f"{name}.bin"
    binpath.write_bytes(data)
    (build_dir / f"{name}.info").write_text(info_file(binpath, base, len(data), ranges, labels, block.get("sizes")))
    raw = subprocess.run(["da65", "-i", str(build_dir / f"{name}.info")], capture_output=True, text=True, check=True).stdout
    title = f"{getattr(sym, 'TITLE', ROOT.name)} – block '{name}' ${base:04X}–${base + len(data) - 1:04X}"
    src = postprocess(raw, title, notes, inline)
    dst = ROOT / "src" / f"{name}.s"
    if check_only:
        if not dst.exists():
            print(f"{name}: src/{name}.s missing; run without --check first")
            return False
        src = dst.read_text()
    else:
        dst.parent.mkdir(exist_ok=True)
        dst.write_text(src)

    with tempfile.TemporaryDirectory() as td:
        s = Path(td) / f"{name}.s"
        s.write_text(src)
        out = Path(td) / f"{name}.out"
        subprocess.run(["cl65", "-t", "none", "--start-addr", f"0x{base:04X}", "-o", str(out), str(s)], check=True, cwd=td)
        rebuilt = out.read_bytes()
    # A PRG rebuild keeps its load address so it can be run; other blocks are raw bytes.
    (build_dir / (f"{name}.prg" if header else f"{name}.rebuilt.bin")).write_bytes(header + rebuilt)
    ok = rebuilt == data
    code_pct = 100 * len(code) / len(data) if data else 0
    print(f"{name}: ${base:04X}–${base + len(data) - 1:04X}, {len(data)} bytes, traced code {code_pct:.0f}%, "
          f"reassembly {'IDENTICAL' if ok else 'DIFFERS'}")
    if bad:
        print(f"  trace stopped at unknown opcodes: {' '.join(f'${a:04X}' for a in sorted(set(bad)))}")
    if not ok:
        first = next((i for i, (x, y) in enumerate(zip(rebuilt, data)) if x != y), min(len(rebuilt), len(data)))
        print(f"  first difference at ${base + first:04X}; rebuilt {len(rebuilt)} bytes vs {len(data)}")
    return ok


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="rebuild and compare only; don't rewrite src/")
    args = ap.parse_args()
    sym = load_symbols()
    ok = all([build(b, sym, args.check) for b in sym.BLOCKS])
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
